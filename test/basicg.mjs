import fs from 'node:fs';
import assert from 'node:assert/strict';
import {IQ151} from '../src/iq151.js';
const rom=(name)=>new Uint8Array(fs.readFileSync(new URL(name,import.meta.url)));
const monitor=rom('../roms/Monitor-std.rom');
const basicg=rom('../modules/BasicG.rom');
const basicg2=rom('../modules/BasicG2.rom');
const m=new IQ151({video:'VIDEO64',grafik:true});m.loadMonitor(monitor);
assert.equal(m.memRead(0xb000),255,'no graphics ROM before BASIC G is inserted');
m.loadBasicG(basicg,basicg2);m.reset();
for (let i=0;i<basicg.length;i++) assert.equal(m.memRead(0xc800+i),basicg[i]);
for (let i=0;i<basicg2.length;i++) assert.equal(m.memRead(0xb000+i),basicg2[i]);
m.memWrite(0xb000,255);assert.equal(m.memRead(0xb000),basicg2[0]);
m.memWrite(0xc800,255);assert.equal(m.memRead(0xc800),basicg[0]);
const advance=(n)=>{for(let i=0;i<n;i++)m.advanceWallTime(20)};
const press=(k)=>{assert.equal(m.setKey(k,true),true,`key ${k}`);advance(5);m.setKey(k,false);advance(12)};
const type=(s)=>{for (const c of s) press(c.charCodeAt(0));press(13);advance(30)};
const screen=()=>Array.from({length:32},(_,r)=>Array.from(m.vram.slice(r*64,r*64+64),x=>String.fromCharCode(x&127)).join('')).join('\n');
advance(100);
console.log('BOOT PC',m.cpu.pc.toString(16),'screen',screen().replace(/\s+/g,' ').slice(0,160));
assert.match(screen(),/BASIC/,'BASIC G banner');assert.match(screen(),/READY/,'BASIC G prompt');
type('PRINT 42');assert.match(screen(),/42/);
console.log('After print',screen().replace(/\s+/g,' ').slice(-160));
console.log('Graphics ports after start',m.grafik.control.toString(16),m.grafik.portC.toString(16));
console.log('PASS: BASIC G boots and executes PRINT 42 through actual ROM');
