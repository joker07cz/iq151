import fs from 'node:fs';
import assert from 'node:assert/strict';
import {IQ151} from '../src/iq151.js';
import {rasterizeComposite} from '../src/iq151_video.js';
const rom=name=>new Uint8Array(fs.readFileSync(new URL(name,import.meta.url)));
const m=new IQ151({video:'VIDEO64',grafik:true});
m.loadMonitor(rom('../roms/Monitor-std.rom'));
m.loadBasicG(rom('../modules/BasicG.rom'),rom('../modules/BasicG2.rom'));
m.reset();
const advance=(n)=>{for(let i=0;i<n;i++)m.advanceWallTime(20)};
const press=k=>{assert.equal(m.setKey(k,true),true,`key ${k}`);advance(3);m.setKey(k,false);advance(6)};
const type=(s)=>{for (const c of s) press(c.charCodeAt(0));press(13);advance(30)};
const screen=()=>Array.from({length:32},(_,r)=>Array.from(m.vram.slice(r*64,r*64+64),x=>String.fromCharCode(x&127)).join('')).join('\n');
const stats=()=>({nonzero:m.grafik.vram.filter(Boolean).length,sum:m.grafik.vram.reduce((s,x)=>s+x,0),picPortC:m.grafik.portC.toString(16),pc:m.cpu.pc.toString(16),irq:m.irqCount,scr:screen().replace(/\s+/g,' ').slice(-110)});
advance(80); console.log('initial',stats());
type('ERASE 255');console.log('ERASE255',stats());
assert.equal(m.grafik.vram.filter(x=>x===255).length,16384,'BASIC G ERASE 255 fills the entire GRAFIK RAM');
type('VIDEO 1');console.log('VIDEO1',stats());
assert.equal(m.grafik.visible,true,'BASIC G VIDEO 1 enables GRAFIK display');
type('ERASE 0');console.log('ERASE0',stats());
assert.equal(m.grafik.vram.filter(Boolean).length,0,'BASIC G ERASE 0 clears GRAFIK RAM');
type('FRAME');console.log('FRAME',stats());
assert.ok(m.grafik.vram.filter(Boolean).length>100,'BASIC G FRAME draws into GRAFIK RAM');
const font=rom('../roms/chars.bin');
const picture=new Uint8ClampedArray(512*512*4), without=new Uint8ClampedArray(512*512*4);
rasterizeComposite(m.vram,font,'VIDEO64',m.grafik,picture);
// Note: use a blank GRAFIK object for text-only composite to preserve 512x512 geometry
const blank={visible:false,vram:m.grafik.vram};
rasterizeComposite(m.vram,font,'VIDEO64',blank,without);
let different=0;for(let i=0;i<picture.length;i+=4) if(picture[i]!==without[i])different++;
assert.ok(different>100,`GRAFIK FRAME must change displayed pixels (different=${different})`);
console.log('PASS: BASIC G ERASE 255, VIDEO 1, ERASE 0, FRAME draw through original ROM and display',different);
